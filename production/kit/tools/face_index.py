"""Regenerate characters/faceIndex.js (FACE_FILES) from public/faces, and the face contact sheet in visual_library.
Run from production/: python -I kit/tools/face_index.py"""
import os, json
from PIL import Image, ImageDraw
names = sorted(f[:-4] for f in os.listdir("kit/public/faces") if f.endswith(".png"))
open("kit/characters/faceIndex.js", "w").write("// Generated by kit/tools/face_index.py from public/faces/*.png (without .png). Re-run after adding faces.\n"
    "export const FACE_FILES = new Set(" + json.dumps(names) + ");\n")
sets = sorted({n.split("_neutral")[0] for n in names if n.endswith("_neutral")})
ex = ["neutral", "happy", "smug", "angry", "shock", "laugh"]; T = 150
sheet = Image.new("RGB", (240 + T * len(ex), T * len(sets)), "white"); dr = ImageDraw.Draw(sheet)
for r, s in enumerate(sets):
    dr.text((6, r * T + T // 2 - 6), s, fill=(0, 0, 0))
    for c, e in enumerate(ex):
        im = Image.open(f"kit/public/faces/{s}_{e}.png").convert("RGBA").crop((200, 180, 824, 804)).resize((T, T))
        bg = Image.new("RGBA", (T, T), (246, 245, 242, 255)); bg.alpha_composite(im); sheet.paste(bg.convert("RGB"), (240 + c * T, r * T))
sheet.save("visual_library/faces_sheet.png"); print(len(names), "face files,", len(sets), "face sets")
